#!/usr/bin/env bash
# Runs ONLY inside the already-running disposable, socket-only PostgreSQL fixture.
# No Supabase access, no real user records and no paid infrastructure.
set -euo pipefail
test -n "${PGHOST:-}" && test -n "${PGUSER:-}"
migration="migrations/NOT_APPLIED_V44_SUBCATEGORIES.sql"
for case_name in new existing_nullable; do
  database="v44_${case_name}_fixture"
  createdb "$database"
  psql -X -v ON_ERROR_STOP=1 -d "$database" <<'SQL'
CREATE TABLE public.sooqak_listings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 category text NOT NULL,
 status text NOT NULL DEFAULT 'active',
 hidden_at timestamptz
);
ALTER TABLE public.sooqak_listings ENABLE ROW LEVEL SECURITY;
INSERT INTO public.sooqak_listings(category,status) VALUES('سيارات','active');
SQL
  if [[ "$case_name" == "existing_nullable" ]]; then
    psql -X -v ON_ERROR_STOP=1 -d "$database" <<'SQL'
ALTER TABLE public.sooqak_listings ADD COLUMN subcategory text;
ALTER TABLE public.sooqak_listings ADD COLUMN specifications jsonb;
SQL
  fi
  # Idempotency: a second application must not erase data or recreate constraints.
  psql -X -v ON_ERROR_STOP=1 -d "$database" -f "$migration" >/dev/null
  psql -X -v ON_ERROR_STOP=1 -d "$database" -f "$migration" >/dev/null

  result=$(psql -XAt -v ON_ERROR_STOP=1 -d "$database" <<'SQL'
SELECT CASE WHEN
  (SELECT COUNT(*)=1 FROM public.sooqak_listings WHERE category='سيارات' AND specifications='{}'::jsonb)
  AND (SELECT COUNT(*)=2 FROM pg_constraint WHERE conrelid='public.sooqak_listings'::regclass AND conname IN ('sooqak_listings_subcategory_v44_check','sooqak_listings_specs_v44_check'))
  AND (SELECT attnotnull FROM pg_attribute WHERE attrelid='public.sooqak_listings'::regclass AND attname='specifications')
  AND (SELECT relrowsecurity FROM pg_class WHERE oid='public.sooqak_listings'::regclass)
  AND to_regclass('public.idx_sooqak_listing_category_subcategory_v44') IS NOT NULL
  THEN 'PASS' ELSE 'FAIL' END;
SQL
)
  if [[ "$result" != PASS ]]; then
    echo "V44 fixture failed: schema, legacy data, RLS, or index (${case_name})" >&2
    exit 1
  fi
  if psql -X -v ON_ERROR_STOP=1 -d "$database" -c "INSERT INTO public.sooqak_listings(category,subcategory) VALUES('عقارات','')" >/dev/null 2>&1; then
    echo "V44 accepted empty subcategory unexpectedly" >&2;exit 1
  fi
  if psql -X -v ON_ERROR_STOP=1 -d "$database" -c "INSERT INTO public.sooqak_listings(category,specifications) VALUES('عقارات','[]'::jsonb)" >/dev/null 2>&1; then
    echo "V44 accepted non-object specifications unexpectedly" >&2;exit 1
  fi
  if psql -X -v ON_ERROR_STOP=1 -d "$database" -c "INSERT INTO public.sooqak_listings(category,specifications) VALUES('عقارات',NULL)" >/dev/null 2>&1; then
    echo "V44 accepted null specifications unexpectedly" >&2;exit 1
  fi
  echo "Verified V44 ${case_name}: twice-applied migration, legacy rows, RLS unchanged, constraints and index."
done
